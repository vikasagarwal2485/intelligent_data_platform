#!/usr/bin/env python3
"""Generate docs/traceability.md from the OpenSpec specs and phase proposals.

Traceability chain: Scenario (SCN-*) <- Requirement (REQ-*) in specs, linked to
the phase(s) whose proposal 'What Changes' cite the REQ id, and the code paths
named in those items. The phase proposals are the historical record, so a cited
path that no longer exists is kept but marked "(removed)".

Phase proposals are read from active (`openspec/changes/phase-*`) and archived
(`openspec/changes/archive/<date>-phase-*`) changes.

Run from the repo root:  python docs/gen_traceability.py
"""
from __future__ import annotations

import re
from pathlib import Path

DOCS = Path(__file__).resolve().parent           # docs/
REPO = DOCS.parent
SPECS = REPO / "openspec" / "specs"
CHANGES = REPO / "openspec" / "changes"
OUT = DOCS / "traceability.md"
PHASE_RE = re.compile(r"(?:^|-)phase-(\d+)-")


def _link(path: Path) -> str:
    """Path relative to docs/, for links inside the generated markdown."""
    return Path("..", path.relative_to(REPO)).as_posix()

CAP_NAMES = {
    "FND": "foundation", "SYN": "synthetic-data", "BRZ": "bronze-ingestion",
    "SLV": "silver-curation", "GLD": "gold-features", "ML": "ml-models",
    "SRV": "serving-api", "STR": "streaming-kafka", "PLT": "platform-deployment",
    "ORC": "orchestration", "MCP": "mcp-analytics",
}
REQ_RE = re.compile(r"^### Requirement:\s+(REQ-([A-Z]+)-\d{2})\s+—\s+(.*)$")
SCN_RE = re.compile(r"^#### Scenario:\s+(SCN-[A-Z]+-\d{2}\.\d+)\s+—\s+(.*)$")
PATH_RE = re.compile(r"`([^`]*(?:/[^`]*|\.(?:py|yaml|yml|sh|toml))[^`]*)`")
REQREF_RE = re.compile(r"REQ-[A-Z]+-\d{2}")


def parse_specs():
    """Return {req_id: {title, cap, scenarios:[(id,title)]}} in file order."""
    reqs: dict[str, dict] = {}
    for spec in sorted(SPECS.glob("*/spec.md")):
        cur = None
        for line in spec.read_text().splitlines():
            m = REQ_RE.match(line)
            s = SCN_RE.match(line)
            if m:
                cur = m.group(1)
                reqs[cur] = {"title": m.group(3), "cap": m.group(2),
                             "scenarios": [], "spec": _link(spec)}
            elif s and cur:
                reqs[cur]["scenarios"].append((s.group(1), s.group(2)))
    return reqs


FILEISH_RE = re.compile(r"^[\w.*\-]+(?:/[\w.*\-{}<>]+)*/?$")
_SKIP_DIRS = {".venv", ".git", "node_modules", "archive", "__pycache__"}


def _exists(path: str) -> bool | None:
    """Whether a cited code path still exists: True/False, or None when the token
    isn't a plain repository path (a URL, an s3:// location, an API route, prose)."""
    p = path
    if not p or p != p.strip() or "://" in p or p.startswith("/") or "REQ-" in p or not FILEISH_RE.match(p):
        return None
    if "<" in p or "{" in p:
        return None                                   # templated, e.g. <prefix>
    for base in (REPO, REPO / "src" / "idp"):         # repo-relative or package-relative
        if any(base.glob(p.rstrip("/"))):
            return True
    if "/" not in p.rstrip("/"):                      # a bare file name: anywhere in the repo
        return any(f for f in REPO.rglob(p)
                   if not _SKIP_DIRS.intersection(f.relative_to(REPO).parts))
    return False


def _code(path: str) -> str:
    return f"`{path}` (removed)" if _exists(path) is False else f"`{path}`"


def parse_proposals():
    """Return {req_id: [(phase_num, phase_slug, [code_paths])]}."""
    impl: dict[str, list] = {}
    props = [*CHANGES.glob("phase-*/proposal.md"), *CHANGES.glob("archive/*phase-*/proposal.md")]
    for prop in sorted(props):
        m = PHASE_RE.search(prop.parent.name)
        if not m:
            continue
        slug = _link(prop)
        num = int(m.group(1))
        text = prop.read_text()
        # only the What Changes section
        wc = text.split("## What Changes", 1)
        body = wc[1].split("\n## ", 1)[0] if len(wc) > 1 else ""
        for line in body.splitlines():
            ids = set(REQREF_RE.findall(line))
            if not ids:
                continue
            paths = PATH_RE.findall(line)
            for rid in ids:
                impl.setdefault(rid, []).append((num, slug, paths))
    return impl


def main():
    reqs = parse_specs()
    impl = parse_proposals()

    total_scn = sum(len(r["scenarios"]) for r in reqs.values())
    lines = [
        "# Traceability Matrix",
        "",
        "> Generated by `docs/gen_traceability.py` — do not edit by hand.",
        "> Re-run after changing specs or proposals.",
        "",
        f"**Coverage:** {len(reqs)} requirements · {total_scn} scenarios · "
        f"{len({p for v in impl.values() for p,_,_ in v})} phases.",
        "",
        "## Summary (Requirement → Phase)",
        "",
        "| Requirement | Title | Capability | Scenarios | Phase(s) |",
        "|---|---|---|---|---|",
    ]
    for rid, r in reqs.items():
        phases = sorted({p for p, _, _ in impl.get(rid, [])})
        ph = ", ".join(f"P{p}" for p in phases) or "—"
        lines.append(
            f"| `{rid}` | {r['title']} | {r['cap']} | {len(r['scenarios'])} | {ph} |"
        )

    # Detailed section grouped by capability
    lines += ["", "## Detail (Requirement → Scenarios → Phase → Code)", ""]
    seen_caps = []
    for rid, r in reqs.items():
        if r["cap"] not in seen_caps:
            seen_caps.append(r["cap"])
            lines += [f"### {r['cap']} — {CAP_NAMES.get(r['cap'], '')}", ""]
        lines.append(f"#### `{rid}` — {r['title']}")
        lines.append(f"- Spec: [`{r['spec']}`]({r['spec']})")
        scn = " · ".join(f"`{sid}` {t}" for sid, t in r["scenarios"]) or "—"
        lines.append(f"- Scenarios: {scn}")
        entries = impl.get(rid, [])
        if entries:
            phs = ", ".join(f"[P{p}]({slug})"
                            for p, slug in sorted({(p, slug) for p, slug, _ in entries}))
            paths = sorted({p for _, _, ps in entries for p in ps})
            lines.append(f"- Implemented in: {phs}")
            if paths:
                lines.append("- Code: " + ", ".join(_code(p) for p in paths))
        else:
            lines.append("- Implemented in: **(unmapped — no proposal references this id)**")
        lines.append("")

    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT.relative_to(REPO)} "
          f"({len(reqs)} reqs, {total_scn} scenarios)")


if __name__ == "__main__":
    main()
