"""Tests for the synthetic data generator."""
from __future__ import annotations

from idp.synthetic.generator import generate, generate_for_tenants


def test_generates_all_entities(small_dataset):
    ds = small_dataset
    assert len(ds.parties) == 80
    assert len(ds.customers) == 80
    assert len(ds.billing_accounts) == 80
    assert len(ds.agreements) == 80
    assert not ds.products.empty
    assert not ds.voice_events.empty
    assert not ds.data_events.empty
    assert not ds.recharge_events.empty
    assert len(ds.labels) == 80


def test_referential_consistency(small_dataset):
    ds = small_dataset
    # SCN-SYN-01.1: every agreement's billing account and customer exist, and every
    # payer and customer party exists
    assert set(ds.agreements["account_id"]).issubset(set(ds.billing_accounts["id"]))
    assert set(ds.agreements["customer_id"]).issubset(set(ds.customers["id"]))
    assert set(ds.billing_accounts["payer_party_id"]).issubset(set(ds.parties["id"]))
    assert set(ds.customers["party_id"]).issubset(set(ds.parties["id"]))
    # an agreement's account is its customer's account
    cust_account = ds.customers.set_index("id")["account_id"]
    assert (ds.agreements["customer_id"].map(cust_account) == ds.agreements["account_id"]).all()
    # every usage event's service_id is a real agreement MSISDN
    msisdns = set(ds.agreements["msisdn"])
    assert set(ds.voice_events["service_id"]).issubset(msisdns)
    assert set(ds.recharge_events["service_id"]).issubset(msisdns)


def test_every_record_is_tenant_stamped(small_dataset):
    for name, df in small_dataset.tables().items():
        assert "tenant_id" in df.columns, name
        assert (df["tenant_id"] == "tenant_a").all(), name


def test_labels_have_both_classes(small_dataset):
    labels = small_dataset.labels
    assert labels["is_fraud"].nunique() == 2
    assert labels["will_default"].nunique() == 2
    assert (labels["true_credit_limit"] >= 5.0).all()
    assert (labels["true_credit_limit"] <= 500.0).all()


def test_deterministic_given_seed():
    a = generate("tenant_a", subscribers=20, days=10, seed=123)
    b = generate("tenant_a", subscribers=20, days=10, seed=123)
    assert a.voice_events.shape == b.voice_events.shape
    assert a.labels.equals(b.labels)


def test_different_tenants_differ():
    ds = generate_for_tenants(["tenant_a", "tenant_b"], subscribers=20, days=10, seed=1)
    a = ds.labels[ds.labels.tenant_id == "tenant_a"]["service_id"].tolist()
    b = ds.labels[ds.labels.tenant_id == "tenant_b"]["service_id"].tolist()
    assert set(a).isdisjoint(set(b))


def test_fraud_subscribers_show_elevated_behaviour(small_dataset):
    """SIM-box fraud subscribers should have higher voice volume on average."""
    ds = small_dataset
    fraud_simbox = ds.labels[ds.labels.fraud_type == "sim_box"]["service_id"]
    normal = ds.labels[ds.labels.fraud_type == "none"]["service_id"]
    vc = ds.voice_events.groupby("service_id").size()
    if len(fraud_simbox) and len(normal):
        assert vc.reindex(fraud_simbox).mean() > vc.reindex(normal).mean()


def test_company_accounts_have_organization_parties():
    # SCN-SYN-01.3 — company parties are organizations without person fields; the
    # organization values come from the suffix, so nothing else changes
    from idp.synthetic.generator import generate
    ds = generate("tenant_a", subscribers=150, days=5, seed=7)
    parties = ds.parties.set_index("id")
    company = set(ds.billing_accounts.loc[ds.billing_accounts["is_company"], "payer_party_id"])
    assert company, "the sample should contain company accounts"
    orgs = parties[parties["party_type"] == "organization"]
    assert set(orgs.index) == company
    assert orgs[["first_name", "last_name", "date_of_birth"]].isna().all().all()
    assert orgs["organization_name"].str.startswith("Company ").all()
    assert (orgs["organization_type"] == "company").all()
    people = parties[parties["party_type"] == "individual"]
    assert len(people) + len(orgs) == len(parties)
    assert people[["first_name", "last_name", "date_of_birth"]].notna().all().all()
    assert people[["organization_name", "organization_type"]].isna().all().all()


def test_former_model_values_are_unchanged():
    # SCN-SYN-01.3: customers and billing accounts reorganize the former values. The
    # fixture was generated by the former model (parties with role/account_id,
    # accounts with account_segment/party_id) with the same parameters.
    import json
    from pathlib import Path

    from idp.common.records import to_records

    former = json.loads((Path(__file__).parent / "fixtures" / "former_model_dataset.json").read_text())
    params = former.pop("_params")
    ds = generate_for_tenants(params["tenants"], subscribers=params["subscribers"], days=params["days"],
                              fraud_rate=params["fraud_rate"], seed=params["seed"])
    by_id = lambda rows: {r["id"]: r for r in rows}
    customers = by_id(to_records(ds.customers))
    cust_of_account = {c["account_id"]: c for c in customers.values()}
    cust_of_party = {c["party_id"]: c for c in customers.values()}

    accounts = by_id(to_records(ds.billing_accounts))
    assert set(accounts) == {a["id"] for a in former["accounts"]}
    for old in former["accounts"]:
        new = accounts[old["id"]]
        assert new["payer_party_id"] == old["party_id"]
        assert cust_of_account[old["id"]]["segment"] == old["account_segment"]
        assert cust_of_account[old["id"]]["valid_from"] == old["valid_from"]
        assert cust_of_account[old["id"]]["party_id"] == old["party_id"]
        rest = {k: v for k, v in old.items() if k not in ("party_id", "account_segment")}
        assert {k: new[k] for k in rest} == rest

    parties = by_id(to_records(ds.parties))
    for old in former["parties"]:
        assert cust_of_party[old["id"]]["role"] == old["role"]
        assert cust_of_party[old["id"]]["account_id"] == old["account_id"]
        assert parties[old["id"]] == {k: v for k, v in old.items() if k not in ("role", "account_id")}

    agreements = by_id(to_records(ds.agreements))
    for old in former["agreements"]:
        new = agreements[old["id"]]
        assert new["customer_id"] == cust_of_account[old["account_id"]]["id"]
        assert {k: v for k, v in new.items() if k != "customer_id"} == old

    assert sorted(to_records(ds.products), key=lambda r: r["id"]) == \
        sorted(former["products"], key=lambda r: r["id"])
